SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    object_count NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') != 'PMOWN'
        OR SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001, 'PMOWN 계정과 스키마에서 실행해주세요.');
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM ALL_TABLES
    WHERE OWNER = 'PMOWN' AND TABLE_NAME = 'TH_PM_SMLT_EXCN_LOG';

    IF object_count = 0 THEN
        DBMS_OUTPUT.PUT_LINE('TH_PM_SMLT_EXCN_LOG 테이블이 없습니다.');
        RETURN;
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM ALL_DEPENDENCIES
    WHERE REFERENCED_OWNER = 'PMOWN' AND REFERENCED_NAME = 'TH_PM_SMLT_EXCN_LOG';

    IF object_count != 0 THEN
        RAISE_APPLICATION_ERROR(-20002, '제거 대상 테이블을 참조하는 DB 객체가 있습니다.');
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM ALL_CONSTRAINTS C
    JOIN ALL_CONSTRAINTS P ON P.OWNER = C.R_OWNER AND P.CONSTRAINT_NAME = C.R_CONSTRAINT_NAME
    WHERE C.CONSTRAINT_TYPE = 'R'
      AND P.OWNER = 'PMOWN' AND P.TABLE_NAME = 'TH_PM_SMLT_EXCN_LOG';

    IF object_count != 0 THEN
        RAISE_APPLICATION_ERROR(-20003, '제거 대상 테이블을 참조하는 외래키가 있습니다.');
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM ALL_SYNONYMS
    WHERE TABLE_OWNER = 'PMOWN' AND TABLE_NAME = 'TH_PM_SMLT_EXCN_LOG';

    IF object_count != 0 THEN
        RAISE_APPLICATION_ERROR(-20004, '제거 대상 테이블의 동의어가 있습니다.');
    END IF;

    EXECUTE IMMEDIATE 'DROP TABLE PMOWN.TH_PM_SMLT_EXCN_LOG';
    DBMS_OUTPUT.PUT_LINE('TH_PM_SMLT_EXCN_LOG 테이블을 제거했습니다.');
END;
