-- PMOWN.DROP_TMP(BASE_DT) 를 표준명 PMOWN.TN_PM_SMLT_DALY_CRTR_YMD(CRTR_YMD) 로 교체한다.
-- CastApiMapper.selectBaseYmdForCalibration 이 새 테이블을 읽는 코드와 같은 배포 창에서 적용한다.
--
-- (1) 사전 점검 → (2) 생성 → (3) 이관 → (4) 검증 순서로 실행한다.
-- (5) DROP_TMP 삭제는 새 코드 배포를 확인한 뒤에 실행한다. (6) 은 복구용이다.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- (1) 사전 점검 — 기존 컬럼 타입과 값. 이관식은 BASE_DT 가 DATE 라는 전제다 (현행 쿼리와 같다)
SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'PMOWN'
  AND TABLE_NAME = 'DROP_TMP'
ORDER BY COLUMN_ID;

SELECT BASE_DT FROM PMOWN.DROP_TMP ORDER BY BASE_DT;

SELECT OWNER, NAME, TYPE
FROM ALL_DEPENDENCIES
WHERE REFERENCED_OWNER = 'PMOWN'
  AND REFERENCED_NAME = 'DROP_TMP';

-- (2) 생성
CREATE TABLE "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"
(
  "CRTR_YMD" VARCHAR2(8) NOT NULL ENABLE VALIDATE,
  "USE_YN" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE VALIDATE,
  "FRST_RGTR_ID" VARCHAR2(40),
  "FRST_RGTR_IP_ADDR" VARCHAR2(23),
  "FRST_REG_DT" TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
  "LAST_MDFR_ID" VARCHAR2(40),
  "LAST_MDFR_IP_ADDR" VARCHAR2(23),
  "LAST_MDFCN_DT" TIMESTAMP(6),
  CONSTRAINT "TN_PM_SMLT_DALY_CRTR_YMD_PK" PRIMARY KEY ("CRTR_YMD"),
  CONSTRAINT "TN_PM_SMLT_DALY_CRTR_YMD_CK1" CHECK (REGEXP_LIKE("CRTR_YMD", '^[0-9]{8}$')),
  CONSTRAINT "TN_PM_SMLT_DALY_CRTR_YMD_CK2" CHECK ("USE_YN" IN ('Y', 'N'))
);

COMMENT ON TABLE "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD" IS 'PM_시뮬레이션일일기준일자';
COMMENT ON COLUMN "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"."CRTR_YMD" IS '기준일자(YYYYMMDD)';
COMMENT ON COLUMN "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"."USE_YN" IS '사용여부';
COMMENT ON COLUMN "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"."FRST_RGTR_ID" IS '최초등록자아이디';
COMMENT ON COLUMN "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"."FRST_RGTR_IP_ADDR" IS '최초등록자IP주소';
COMMENT ON COLUMN "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"."FRST_REG_DT" IS '최초등록일시';
COMMENT ON COLUMN "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"."LAST_MDFR_ID" IS '최종수정자아이디';
COMMENT ON COLUMN "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"."LAST_MDFR_IP_ADDR" IS '최종수정자IP주소';
COMMENT ON COLUMN "PMOWN"."TN_PM_SMLT_DALY_CRTR_YMD"."LAST_MDFCN_DT" IS '최종수정일시';

-- (3) 이관 — 현행 쿼리가 쓰던 MAX(BASE_DT) 한 건만 사용(Y) 행으로 옮긴다
INSERT INTO PMOWN.TN_PM_SMLT_DALY_CRTR_YMD (CRTR_YMD, USE_YN, FRST_RGTR_ID, FRST_RGTR_IP_ADDR)
SELECT TO_CHAR(MAX(BASE_DT), 'YYYYMMDD'), 'Y', 'SYSTEM', '0.0.0.0'
FROM PMOWN.DROP_TMP
HAVING MAX(BASE_DT) IS NOT NULL;

-- (4) 검증 — 두 값이 같아야 COMMIT 한다
SELECT
    (SELECT NVL(TO_CHAR(MAX(BASE_DT), 'YYYYMMDD'), TO_CHAR(SYSDATE, 'YYYYMMDD')) FROM PMOWN.DROP_TMP) AS OLD_YMD,
    (SELECT NVL(MAX(CRTR_YMD), TO_CHAR(SYSDATE, 'YYYYMMDD')) FROM PMOWN.TN_PM_SMLT_DALY_CRTR_YMD WHERE USE_YN = 'Y') AS NEW_YMD
FROM DUAL;

