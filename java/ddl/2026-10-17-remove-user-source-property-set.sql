SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    n NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001, 'PMOWN 스키마에서 실행해주세요.');
    END IF;

    SELECT COUNT(*) INTO n
    FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'PMOWN'
      AND TABLE_NAME = 'TN_PM_SMLT_USER_MSTR'
      AND COLUMN_NAME = 'SRC_PRPT_SET_RSRC_ID';
    IF n = 0 THEN
        DBMS_OUTPUT.PUT_LINE('SRC_PRPT_SET_RSRC_ID 컬럼이 이미 없습니다.');
        RETURN;
    END IF;

    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_USER_MSTR
        WHERE SRC_PRPT_SET_RSRC_ID IS NULL OR SRC_PRPT_SET_RSRC_ID != ''PS001'''
        INTO n;
    IF n != 0 THEN
        RAISE_APPLICATION_ERROR(-20002, '원천 PS가 PS001이 아닌 실행이 있습니다. 해당 실행의 PS001 전환 여부를 확인해주세요.');
    END IF;

    SELECT COUNT(*) INTO n
    FROM PMOWN.TN_PM_SMLT_FIX_ATRB_GROUP
    WHERE FIX_ATRB_GROUP_ID = '001' AND DEL_YN = 'N';
    IF n != 1 THEN
        RAISE_APPLICATION_ERROR(-20003, '사용 가능한 기준정보 PS001이 없습니다.');
    END IF;

    EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_USER_MSTR DROP COLUMN SRC_PRPT_SET_RSRC_ID';
END;
/
