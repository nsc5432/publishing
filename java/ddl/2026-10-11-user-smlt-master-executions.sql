MERGE INTO PMOWN.TN_PM_SMLT_LEGACY_ISSUE T USING (
    SELECT 'STNG:'||SMLT_ID ISSUE_KEY,'INVALID_OR_AMBIGUOUS_EXECUTION' REASON FROM PMOWN.TN_PM_SMLT_STNG
    GROUP BY SMLT_ID HAVING COUNT(DISTINCT EXCN_YMD)!=1 OR COUNT(DISTINCT SMLT_TYPE)!=1 OR COUNT(EXCN_YMD)!=COUNT(*) OR COUNT(SMLT_TYPE)!=COUNT(*) OR NOT REGEXP_LIKE(SMLT_ID,'^[0-9]{1,8}$')
) S ON (T.ISSUE_KEY=S.ISSUE_KEY) WHEN NOT MATCHED THEN INSERT (ISSUE_KEY,REASON) VALUES (S.ISSUE_KEY,S.REASON);
MERGE INTO PMOWN.TN_PM_SMLT_MSTR T USING (
    SELECT SMLT_ID,MIN(SMLT_TYPE) SMLT_TYPE,MIN(EXCN_YMD) EXCN_YMD,MIN(SMLT_BGNG_DT) SMLT_BGNG_DT,MAX(SMLT_END_DT) SMLT_END_DT,
        MIN(FRST_RGTR_ID) KEEP (DENSE_RANK FIRST ORDER BY FRST_REG_DT) FRST_RGTR_ID,MIN(FRST_REG_DT) FRST_REG_DT
    FROM PMOWN.TN_PM_SMLT_STNG GROUP BY SMLT_ID
    HAVING COUNT(DISTINCT EXCN_YMD)=1 AND COUNT(DISTINCT SMLT_TYPE)=1 AND COUNT(EXCN_YMD)=COUNT(*) AND COUNT(SMLT_TYPE)=COUNT(*) AND REGEXP_LIKE(SMLT_ID,'^[0-9]{1,8}
) S ON (T.SMLT_ID=S.SMLT_ID)
WHEN NOT MATCHED THEN INSERT (SMLT_ID,SMLT_TYPE,EXCN_YMD,SMLT_STTS,SMLT_BGNG_DT,SMLT_END_DT,FRST_RGTR_ID,FRST_REG_DT)
VALUES (S.SMLT_ID,S.SMLT_TYPE,S.EXCN_YMD,'Finished',S.SMLT_BGNG_DT,S.SMLT_END_DT,S.FRST_RGTR_ID,S.FRST_REG_DT);
DECLARE
    n NUMBER; lock_id VARCHAR2(20); new_id VARCHAR2(8); next_value NUMBER; target_date VARCHAR2(8); date_count NUMBER; reason VARCHAR2(4000);
BEGIN
    SELECT LOCK_ID INTO lock_id FROM PMOWN.TN_PM_SMLT_ID_LOCK WHERE LOCK_ID='EXECUTION' FOR UPDATE;
    SELECT NVL(MAX(TO_NUMBER(SMLT_ID)),0) INTO next_value FROM (
        SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_MSTR
        UNION ALL SELECT SMLT_ID FROM PMOWN.TH_PM_SMLT_FLFMT_HSTRY_LGC WHERE REGEXP_LIKE(SMLT_ID,'^[0-9]{1,8}$')
        UNION ALL SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_USER_MSTR_LGC WHERE REGEXP_LIKE(SMLT_ID,'^[0-9]{1,8}
    );
    FOR r IN (SELECT * FROM PMOWN.TN_PM_SMLT_USER_MSTR_LGC U WHERE NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_LEGACY_EXEC_MAP M WHERE M.OLD_REQ_ID=U.SMLT_REQ_ID) ORDER BY U.FRST_REG_DT,U.SMLT_REQ_ID) LOOP
        reason:=NULL; new_id:=NULL; target_date:=r.EXCN_YMD;
        IF target_date IS NULL THEN
            SELECT COUNT(DISTINCT EXCN_YMD),MIN(EXCN_YMD) INTO date_count,target_date FROM PMOWN.TN_PM_SMLT_STNG WHERE SMLT_ID=r.SMLT_ID;
            IF date_count!=1 THEN reason:='MISSING_OR_AMBIGUOUS_DATE'; END IF;
        END IF;
        IF r.RSLT_SMLT_ID IS NOT NULL THEN
            SELECT COUNT(*) INTO n FROM PMOWN.TN_PM_SMLT_USER_MSTR_LGC WHERE RSLT_SMLT_ID=r.RSLT_SMLT_ID;
            IF n!=1 THEN reason:='MULTIPLE_REQUESTS_ONE_RESULT'; END IF;
            SELECT COUNT(*) INTO n FROM PMOWN.TN_PM_SMLT_MSTR WHERE SMLT_ID=r.RSLT_SMLT_ID AND EXCN_YMD=target_date AND SMLT_TYPE='WhatIf';
            IF n!=1 THEN reason:='UNVERIFIED_RESULT_LINK'; END IF;
            IF reason IS NULL THEN new_id:=r.RSLT_SMLT_ID; END IF;
        ELSIF reason IS NULL THEN
            next_value:=next_value+1;
            IF next_value>99999999 THEN RAISE_APPLICATION_ERROR(-20001,'ID capacity exceeded'); END IF;
            new_id:=TO_CHAR(next_value,'FM00000000');
            INSERT INTO PMOWN.TN_PM_SMLT_MSTR (SMLT_ID,SMLT_TYPE,EXCN_YMD,SMLT_STTS,SMLT_REQ_DT,SMLT_BGNG_DT,SMLT_END_DT,FRST_RGTR_ID,FRST_REG_DT)
            VALUES (new_id,'WhatIf',target_date,r.SMLT_STTS,r.QUEUE_DT,r.EXCT_DT,r.END_DT,r.FRST_RGTR_ID,r.FRST_REG_DT);
        END IF;
        INSERT INTO PMOWN.TN_PM_SMLT_LEGACY_EXEC_MAP VALUES (r.SMLT_ID,r.SMLT_FLFMT_SN,r.SMLT_REQ_ID,r.RSLT_SMLT_ID,new_id,reason);
        IF reason IS NOT NULL THEN
            INSERT INTO PMOWN.TN_PM_SMLT_LEGACY_ISSUE (ISSUE_KEY,REASON) VALUES ('REQ:'||r.SMLT_REQ_ID,reason);
        END IF;
    END LOOP;
END;
