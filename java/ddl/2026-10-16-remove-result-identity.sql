SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    n NUMBER;
    source_count NUMBER;
    backup_count NUMBER;
    diff_count NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001,'PMOWN 스키마에서 실행해주세요.');
    END IF;
    SELECT COUNT(*) INTO n FROM ALL_TABLES
    WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_RESULT_IDENTITY';
    IF n=0 THEN
        DBMS_OUTPUT.PUT_LINE('TN_PM_SMLT_RESULT_IDENTITY가 이미 제거됐습니다.');
        RETURN;
    END IF;
    SELECT COUNT(*) INTO n FROM ALL_DEPENDENCIES
    WHERE REFERENCED_OWNER='PMOWN' AND REFERENCED_NAME='TN_PM_SMLT_RESULT_IDENTITY';
    IF n!=0 THEN
        RAISE_APPLICATION_ERROR(-20002,'RESULT_IDENTITY를 참조하는 DB 객체가 있습니다.');
    END IF;
    SELECT COUNT(*) INTO n
    FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
        ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
    WHERE C.CONSTRAINT_TYPE='R' AND P.OWNER='PMOWN' AND P.TABLE_NAME='TN_PM_SMLT_RESULT_IDENTITY';
    IF n!=0 THEN
        RAISE_APPLICATION_ERROR(-20003,'RESULT_IDENTITY를 참조하는 외래키가 있습니다.');
    END IF;
    SELECT COUNT(*) INTO n FROM ALL_TABLES
    WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_RSID_BAK_1016';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE PMOWN.TN_PM_SMLT_RSID_BAK_1016 AS SELECT * FROM PMOWN.TN_PM_SMLT_RESULT_IDENTITY';
    END IF;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_RESULT_IDENTITY' INTO source_count;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_RSID_BAK_1016' INTO backup_count;
    EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM (
        SELECT SOURCE_KEY,SMLT_ID,PAYLOAD_HASH FROM PMOWN.TN_PM_SMLT_RESULT_IDENTITY
        MINUS
        SELECT SOURCE_KEY,SMLT_ID,PAYLOAD_HASH FROM PMOWN.TN_PM_SMLT_RSID_BAK_1016
    )~' INTO diff_count;
    IF source_count!=backup_count OR diff_count!=0 THEN
        RAISE_APPLICATION_ERROR(-20004,'RESULT_IDENTITY 백업이 원본과 다릅니다.');
    END IF;
    EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM (
        SELECT SOURCE_KEY,SMLT_ID,PAYLOAD_HASH FROM PMOWN.TN_PM_SMLT_RSID_BAK_1016
        MINUS
        SELECT SOURCE_KEY,SMLT_ID,PAYLOAD_HASH FROM PMOWN.TN_PM_SMLT_RESULT_IDENTITY
    )~' INTO diff_count;
    IF diff_count!=0 THEN
        RAISE_APPLICATION_ERROR(-20004,'RESULT_IDENTITY 백업이 원본과 다릅니다.');
    END IF;
    EXECUTE IMMEDIATE 'DROP TABLE PMOWN.TN_PM_SMLT_RESULT_IDENTITY';
    DBMS_OUTPUT.PUT_LINE('RESULT_IDENTITY 제거 완료. 백업: TN_PM_SMLT_RSID_BAK_1016');
END;
/
SELECT TABLE_NAME FROM ALL_TABLES
WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_RESULT_IDENTITY';
