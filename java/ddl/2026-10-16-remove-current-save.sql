SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    n NUMBER;
    source_count NUMBER;
    backup_count NUMBER;
    diff_count NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001,'PMOWN 스키마에서 실행해주세요.');
    END IF;
    SELECT COUNT(*) INTO n FROM ALL_TABLES
    WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_CURRENT_SAVE';
    IF n=0 THEN
        DBMS_OUTPUT.PUT_LINE('TN_PM_SMLT_CURRENT_SAVE가 이미 제거됐습니다.');
        RETURN;
    END IF;
    SELECT COUNT(*) INTO n FROM ALL_DEPENDENCIES
    WHERE REFERENCED_OWNER='PMOWN' AND REFERENCED_NAME='TN_PM_SMLT_CURRENT_SAVE';
    IF n!=0 THEN
        RAISE_APPLICATION_ERROR(-20002,'CURRENT_SAVE를 참조하는 DB 객체가 있습니다.');
    END IF;
    SELECT COUNT(*) INTO n
    FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
        ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
    WHERE C.CONSTRAINT_TYPE='R' AND P.OWNER='PMOWN' AND P.TABLE_NAME='TN_PM_SMLT_CURRENT_SAVE';
    IF n!=0 THEN
        RAISE_APPLICATION_ERROR(-20003,'CURRENT_SAVE를 참조하는 외래키가 있습니다.');
    END IF;
    SELECT COUNT(*) INTO n FROM ALL_TABLES
    WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_SAVE_BAK_1016';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE PMOWN.TN_PM_SMLT_SAVE_BAK_1016 AS SELECT * FROM PMOWN.TN_PM_SMLT_CURRENT_SAVE';
    END IF;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_CURRENT_SAVE' INTO source_count;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_SAVE_BAK_1016' INTO backup_count;
    EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM (
        SELECT OWNER_USER_ID,EXCN_YMD,TMNL_ID,AREA_CD,SAVE_DT FROM PMOWN.TN_PM_SMLT_CURRENT_SAVE
        MINUS
        SELECT OWNER_USER_ID,EXCN_YMD,TMNL_ID,AREA_CD,SAVE_DT FROM PMOWN.TN_PM_SMLT_SAVE_BAK_1016
    )~' INTO diff_count;
    IF source_count!=backup_count OR diff_count!=0 THEN
        RAISE_APPLICATION_ERROR(-20004,'CURRENT_SAVE 백업이 원본과 다릅니다.');
    END IF;
    EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM (
        SELECT OWNER_USER_ID,EXCN_YMD,TMNL_ID,AREA_CD,SAVE_DT FROM PMOWN.TN_PM_SMLT_SAVE_BAK_1016
        MINUS
        SELECT OWNER_USER_ID,EXCN_YMD,TMNL_ID,AREA_CD,SAVE_DT FROM PMOWN.TN_PM_SMLT_CURRENT_SAVE
    )~' INTO diff_count;
    IF diff_count!=0 THEN
        RAISE_APPLICATION_ERROR(-20004,'CURRENT_SAVE 백업이 원본과 다릅니다.');
    END IF;
    EXECUTE IMMEDIATE 'DROP TABLE PMOWN.TN_PM_SMLT_CURRENT_SAVE';
    DBMS_OUTPUT.PUT_LINE('CURRENT_SAVE 제거 완료. 백업: TN_PM_SMLT_SAVE_BAK_1016');
END;
/
SELECT TABLE_NAME FROM ALL_TABLES
WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_CURRENT_SAVE';
