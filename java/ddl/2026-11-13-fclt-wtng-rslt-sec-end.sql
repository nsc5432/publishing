SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- 결과 수신과 조회를 중지한 상태에서 실행한 뒤 SEC_END_DT 기준 코드를 배포한다.
-- Oracle DDL은 자동 커밋된다. 기존 시작시각은 새 PK / 제약 전환까지 남겨 중단 후 재실행해도 10분을 중복 가산하지 않는다.
DECLARE
    bgng_column_count NUMBER;
    end_column_count NUMBER;
    end_nullable VARCHAR2(1);
    moved_count NUMBER := 0;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') != 'PMOWN'
        OR SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001, 'PMOWN 계정과 스키마에서 실행해주세요.');
    END IF;

    SELECT COUNT(*) INTO bgng_column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'TN_PM_SMLT_FCLT_WTNG_RSLT' AND COLUMN_NAME = 'SEC_BGNG_DT';

    SELECT COUNT(*) INTO end_column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'TN_PM_SMLT_FCLT_WTNG_RSLT' AND COLUMN_NAME = 'SEC_END_DT';

    IF bgng_column_count = 0 AND end_column_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20002, '시설 대기 결과의 구간 시각 컬럼을 찾을 수 없습니다.');
    END IF;

    IF bgng_column_count = 1 THEN
        IF end_column_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT ADD (SEC_END_DT TIMESTAMP(0))';
        END IF;

        EXECUTE IMMEDIATE 'UPDATE PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT '
            || 'SET SEC_END_DT = SEC_BGNG_DT + INTERVAL ''10'' MINUTE '
            || 'WHERE SEC_END_DT IS NULL OR SEC_END_DT <> SEC_BGNG_DT + INTERVAL ''10'' MINUTE';
        moved_count := SQL%ROWCOUNT;
        COMMIT;

        SELECT NULLABLE INTO end_nullable
        FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'TN_PM_SMLT_FCLT_WTNG_RSLT' AND COLUMN_NAME = 'SEC_END_DT';

        IF end_nullable = 'Y' THEN
            EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT MODIFY (SEC_END_DT NOT NULL)';
        END IF;

        FOR c IN (
            SELECT CONSTRAINT_NAME
            FROM USER_CONSTRAINTS
            WHERE TABLE_NAME = 'TN_PM_SMLT_FCLT_WTNG_RSLT'
                AND CONSTRAINT_NAME IN ('PK_SMLT_FCLT_WTNG_RSLT', 'CK_WTNG_RSLT_SEC')
        ) LOOP
            EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT DROP CONSTRAINT ' || c.CONSTRAINT_NAME;
        END LOOP;

        EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT '
            || 'ADD CONSTRAINT PK_SMLT_FCLT_WTNG_RSLT PRIMARY KEY '
            || '(SMLT_ID, SMLT_MDL_SN, TMNL_ID, FCLT_TYPE_CD, FCLT_UNIT_CD, SEC_END_DT)';
        EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT '
            || 'ADD CONSTRAINT CK_WTNG_RSLT_SEC CHECK ('
            || 'EXTRACT(SECOND FROM SEC_END_DT) = 0 AND MOD(EXTRACT(MINUTE FROM SEC_END_DT), 10) = 0)';

        EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT DROP COLUMN SEC_BGNG_DT';
    END IF;

    EXECUTE IMMEDIATE 'COMMENT ON COLUMN PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT.SEC_END_DT IS '
        || '''구간종료일시(Asia/Seoul,시작10분후,미포함,CAST결과시각)''';

    DBMS_OUTPUT.PUT_LINE('SEC_END_DT 전환 완료. 시작시각 + 10분으로 이관한 행 수: ' || moved_count);
END;
