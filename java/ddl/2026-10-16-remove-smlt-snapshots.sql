DECLARE fs_no NUMBER; ps_no NUMBER; n NUMBER; old_no NUMBER;
BEGIN
    SELECT NVL(MAX(TO_NUMBER(LAST_NO)),1) INTO fs_no FROM PMOWN.TN_PM_SMLT_ID_LOCK WHERE LOCK_ID='RSRC_FS';
    SELECT NVL(MAX(TO_NUMBER(LAST_NO)),499) INTO ps_no FROM PMOWN.TN_PM_SMLT_ID_LOCK WHERE LOCK_ID='RSRC_PS';
    FOR R IN (SELECT 'FS' KIND,FLT_SCHDL_RSRC_ID ID FROM PMOWN.TN_PM_SMLT_USER_MSTR
        UNION ALL SELECT 'PS',PRPT_STNG_RSRC_ID FROM PMOWN.TN_PM_SMLT_USER_MSTR
        UNION ALL SELECT 'FS',FLT_SCHDL_RSRC_ID FROM PMOWN.TN_PM_SMLT_STNG
        UNION ALL SELECT 'PS',PRPT_SET_RSRC_ID FROM PMOWN.TN_PM_SMLT_STNG) LOOP
        IF R.KIND='FS' AND REGEXP_LIKE(R.ID,'^FS[0-9]{3}$') THEN fs_no:=GREATEST(fs_no,TO_NUMBER(SUBSTR(R.ID,3))); END IF;
        IF R.KIND='PS' AND REGEXP_LIKE(R.ID,'^PS[0-9]{3}$') AND SUBSTR(R.ID,3) BETWEEN '500' AND '998' THEN ps_no:=GREATEST(ps_no,TO_NUMBER(SUBSTR(R.ID,3))); END IF;
    END LOOP;
    SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_LEASE_BAK_1016';
    IF n!=0 THEN
        EXECUTE IMMEDIATE 'SELECT NVL(MAX(TO_NUMBER(RSRC_NO)),1) FROM PMOWN.TN_PM_SMLT_LEASE_BAK_1016 WHERE RSRC_KIND=''FS''' INTO old_no;
        fs_no:=GREATEST(fs_no,old_no);
        EXECUTE IMMEDIATE 'SELECT NVL(MAX(TO_NUMBER(RSRC_NO)),499) FROM PMOWN.TN_PM_SMLT_LEASE_BAK_1016 WHERE RSRC_KIND=''PS''' INTO old_no;
        ps_no:=GREATEST(ps_no,old_no);
    END IF;
    MERGE INTO PMOWN.TN_PM_SMLT_ID_LOCK T USING (SELECT 'RSRC_FS' LOCK_ID,TO_CHAR(fs_no,'FM000') LAST_NO FROM DUAL
        UNION ALL SELECT 'RSRC_PS',TO_CHAR(ps_no,'FM000') FROM DUAL) S ON (T.LOCK_ID=S.LOCK_ID)
    WHEN MATCHED THEN UPDATE SET T.LAST_NO=S.LAST_NO WHEN NOT MATCHED THEN INSERT (LOCK_ID,LAST_NO) VALUES (S.LOCK_ID,S.LAST_NO);
    SELECT COUNT(*) INTO n FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='PMOWN' AND SEQUENCE_NAME='SQ1_TN_PM_SMLT_USER_RSRC';
    IF n!=0 THEN EXECUTE IMMEDIATE 'ALTER SEQUENCE PMOWN.SQ1_TN_PM_SMLT_USER_RSRC NOCYCLE'; END IF;
    SELECT COUNT(*) INTO n FROM PMOWN.TN_PM_SMLT_USER_MSTR WHERE SRC_PRPT_SET_RSRC_ID IS NULL;
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20009,'원천 PropertySet 참조가 누락됐습니다.'); END IF;
END;
/
