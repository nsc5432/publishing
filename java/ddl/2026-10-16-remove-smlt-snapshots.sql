SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE n NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA')!='PMOWN' THEN RAISE_APPLICATION_ERROR(-20001,'PMOWN 스키마에서 실행해주세요.'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_MSTR';
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20002,'공통 마스터 제거 전환을 먼저 완료해주세요.'); END IF;
    SELECT COUNT(*) INTO n FROM PMOWN.TN_PM_SMLT_USER_MSTR U WHERE U.SMLT_STTS IN ('New','Executing')
        OR (U.SMLT_STTS='Finished' AND NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_STNG S WHERE S.SMLT_ID=U.SMLT_ID));
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20003,'진행 중이거나 결과가 미도착한 사용자 요청이 있습니다.'); END IF;
    SELECT COUNT(*) INTO n FROM (SELECT PRPT_STNG_RSRC_ID FROM PMOWN.TN_PM_SMLT_USER_MSTR
        WHERE REGEXP_LIKE(PRPT_STNG_RSRC_ID,'^PS[0-9]{3}$') AND SUBSTR(PRPT_STNG_RSRC_ID,3) BETWEEN '500' AND '998' GROUP BY PRPT_STNG_RSRC_ID HAVING COUNT(*)>1);
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20004,'재사용된 사용자 PS ID를 실행별로 분리해주세요.'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_DEPENDENCIES WHERE REFERENCED_OWNER='PMOWN' AND REFERENCED_NAME IN
        ('TN_PM_SMLT_COND_SNAPSHOT','TN_PM_SMLT_INPUT_SNAPSHOT','TN_PM_SMLT_RSRC_LEASE');
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20006,'제거 대상 테이블을 참조하는 DB 객체가 있습니다.'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
    WHERE C.CONSTRAINT_TYPE='R' AND P.OWNER='PMOWN' AND P.TABLE_NAME IN
        ('TN_PM_SMLT_COND_SNAPSHOT','TN_PM_SMLT_INPUT_SNAPSHOT','TN_PM_SMLT_RSRC_LEASE');
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20007,'제거 대상 테이블을 참조하는 외래키가 있습니다.'); END IF;
END;
/
DECLARE
    PROCEDURE backup_table(tbl VARCHAR2,bak VARCHAR2,keys VARCHAR2,differences VARCHAR2) IS n NUMBER; a NUMBER; b NUMBER; diff NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME=tbl;
        IF n=0 THEN RETURN; END IF;
        SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME=bak;
        IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE PMOWN.'||bak||' AS SELECT * FROM PMOWN.'||tbl; END IF;
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.'||tbl INTO a;
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.'||bak INTO b;
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.'||tbl||' S FULL OUTER JOIN PMOWN.'||bak||' B ON ('||keys||') WHERE S.SMLT_ID IS NULL OR B.SMLT_ID IS NULL OR '||differences INTO diff;
        IF a!=b OR diff!=0 THEN RAISE_APPLICATION_ERROR(-20008,'백업이 원본과 다릅니다: '||tbl); END IF;
    END;
BEGIN
    backup_table('TN_PM_SMLT_COND_SNAPSHOT','TN_PM_SMLT_COND_BAK_1016','S.SMLT_ID=B.SMLT_ID AND S.TMNL_ID=B.TMNL_ID AND S.AREA_CD=B.AREA_CD','DBMS_LOB.COMPARE(S.PAYLOAD,B.PAYLOAD)!=0');
    backup_table('TN_PM_SMLT_INPUT_SNAPSHOT','TN_PM_SMLT_INPUT_BAK_1016','S.SMLT_ID=B.SMLT_ID AND S.RESOURCE_TYPE=B.RESOURCE_TYPE AND S.RESOURCE_ID=B.RESOURCE_ID','DECODE(S.SOURCE_ID,B.SOURCE_ID,0,1)=1 OR DBMS_LOB.COMPARE(S.PAYLOAD,B.PAYLOAD)!=0');
    backup_table('TN_PM_SMLT_RSRC_LEASE','TN_PM_SMLT_LEASE_BAK_1016','S.RSRC_KIND=B.RSRC_KIND AND S.RSRC_NO=B.RSRC_NO','S.SMLT_ID!=B.SMLT_ID');
END;
/
DECLARE
    PROCEDURE add_column_once(tbl VARCHAR2,col VARCHAR2,definition VARCHAR2) IS n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='PMOWN' AND TABLE_NAME=tbl AND COLUMN_NAME=col;
        IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.'||tbl||' ADD ('||col||' '||definition||')'; END IF;
    END;
BEGIN
    add_column_once('TN_PM_SMLT_USER_MSTR','SRC_PRPT_SET_RSRC_ID','VARCHAR2(100)');
    add_column_once('TN_PM_SMLT_FCLTY_OPNG_DPTGT_ATRB','GNRL_SRCH_CNTOM','NUMBER(20,0)');
    add_column_once('TN_PM_SMLT_FCLTY_OPNG_DPTGT_ATRB','SMART_PASS_SRCH_CNTOM','NUMBER(20,0)');
END;
