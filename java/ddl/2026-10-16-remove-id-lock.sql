SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    n NUMBER;
    source_count NUMBER;
    backup_count NUMBER;
    diff_count NUMBER;
    last_no NUMBER;
    used_no NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001,'PMOWN 스키마에서 실행해주세요.');
    END IF;
    SELECT COUNT(*) INTO n FROM ALL_TABLES
    WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_ID_LOCK';
    IF n=0 THEN
        DBMS_OUTPUT.PUT_LINE('TN_PM_SMLT_ID_LOCK이 이미 제거됐습니다.');
        RETURN;
    END IF;
    SELECT COUNT(*) INTO n FROM ALL_DEPENDENCIES
    WHERE REFERENCED_OWNER='PMOWN' AND REFERENCED_NAME='TN_PM_SMLT_ID_LOCK';
    IF n!=0 THEN
        RAISE_APPLICATION_ERROR(-20002,'ID_LOCK을 참조하는 DB 객체가 있습니다.');
    END IF;
    SELECT COUNT(*) INTO n
    FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
        ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
    WHERE C.CONSTRAINT_TYPE='R' AND P.OWNER='PMOWN' AND P.TABLE_NAME='TN_PM_SMLT_ID_LOCK';
    IF n!=0 THEN
        RAISE_APPLICATION_ERROR(-20003,'ID_LOCK을 참조하는 외래키가 있습니다.');
    END IF;
    -- LAST_NO가 요청/결과의 최대 번호보다 크면 그 사이 번호가 제거 후 다시 할당된다
    FOR K IN (SELECT 'FS' KIND, 2 MIN_NO, 999 MAX_NO FROM DUAL UNION ALL SELECT 'PS', 500, 998 FROM DUAL) LOOP
        EXECUTE IMMEDIATE 'SELECT MAX(TO_NUMBER(LAST_NO)) FROM PMOWN.TN_PM_SMLT_ID_LOCK WHERE LOCK_ID=:1'
            INTO last_no USING 'RSRC_' || K.KIND;
        SELECT NVL(MAX(NO), K.MIN_NO - 1) INTO used_no FROM (
            SELECT CASE WHEN REGEXP_LIKE(ID, '^' || K.KIND || '[0-9]{3}$') THEN TO_NUMBER(SUBSTR(ID, 3)) END NO FROM (
                SELECT DECODE(K.KIND, 'FS', FLT_SCHDL_RSRC_ID, PRPT_STNG_RSRC_ID) ID FROM PMOWN.TN_PM_SMLT_USER_MSTR
                UNION ALL
                SELECT DECODE(K.KIND, 'FS', FLT_SCHDL_RSRC_ID, PRPT_SET_RSRC_ID) FROM PMOWN.TN_PM_SMLT_STNG
            )
        ) WHERE NO BETWEEN K.MIN_NO AND K.MAX_NO;
        IF NVL(last_no, 0) > used_no THEN
            RAISE_APPLICATION_ERROR(-20005, K.KIND || ' LAST_NO(' || last_no || ')가 사용된 최대 번호(' || used_no
                || ')보다 큽니다. 그 사이 번호가 CAST에 보낸 적 있는지 확인해주세요.');
        END IF;
    END LOOP;
    SELECT COUNT(*) INTO n FROM ALL_TABLES
    WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_LOCK_BAK_1016';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE PMOWN.TN_PM_SMLT_LOCK_BAK_1016 AS SELECT * FROM PMOWN.TN_PM_SMLT_ID_LOCK';
    END IF;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_ID_LOCK' INTO source_count;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_LOCK_BAK_1016' INTO backup_count;
    EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM (
        SELECT LOCK_ID,LAST_NO FROM PMOWN.TN_PM_SMLT_ID_LOCK
        MINUS
        SELECT LOCK_ID,LAST_NO FROM PMOWN.TN_PM_SMLT_LOCK_BAK_1016
    )~' INTO diff_count;
    IF source_count!=backup_count OR diff_count!=0 THEN
        RAISE_APPLICATION_ERROR(-20004,'ID_LOCK 백업이 원본과 다릅니다.');
    END IF;
    EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM (
        SELECT LOCK_ID,LAST_NO FROM PMOWN.TN_PM_SMLT_LOCK_BAK_1016
        MINUS
        SELECT LOCK_ID,LAST_NO FROM PMOWN.TN_PM_SMLT_ID_LOCK
    )~' INTO diff_count;
    IF diff_count!=0 THEN
        RAISE_APPLICATION_ERROR(-20004,'ID_LOCK 백업이 원본과 다릅니다.');
    END IF;
    EXECUTE IMMEDIATE 'DROP TABLE PMOWN.TN_PM_SMLT_ID_LOCK';
    DBMS_OUTPUT.PUT_LINE('ID_LOCK 제거 완료. 백업: TN_PM_SMLT_LOCK_BAK_1016');
END;
/
SELECT TABLE_NAME FROM ALL_TABLES
WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_ID_LOCK';
