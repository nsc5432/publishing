SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    object_count NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Run as PMOWN');
    END IF;
    SELECT COUNT(*) INTO object_count
    FROM USER_OBJECTS
    WHERE OBJECT_NAME IN (
        'TN_PM_SMLT_CAST_LOG_STNG', 'TH_PM_SMLT_CAST_LOG'
    );
    IF object_count != 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'CAST REST log objects already exist; inspect before applying');
    END IF;
END;
/

CREATE TABLE PMOWN.TN_PM_SMLT_CAST_LOG_STNG (
    CAST_API_TYPE_CD VARCHAR2(30 CHAR) NOT NULL,
    CAST_LOG_TYPE_CD VARCHAR2(10 CHAR) NOT NULL,
    USE_YN CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    FRST_RGTR_ID VARCHAR2(40),
    FRST_RGTR_IP_ADDR VARCHAR2(23),
    FRST_REG_DT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    LAST_MDFR_ID VARCHAR2(40),
    LAST_MDFR_IP_ADDR VARCHAR2(23),
    LAST_MDFCN_DT TIMESTAMP(6),
    CONSTRAINT PK_PM_SMLT_CAST_LOG_STNG PRIMARY KEY (CAST_API_TYPE_CD, CAST_LOG_TYPE_CD),
    CONSTRAINT CK_PM_CASTREST_STNG_API CHECK (
        CAST_API_TYPE_CD IN ('GetResourceInformation', 'GetResource', 'SetResource')
    ),
    CONSTRAINT CK_PM_CASTREST_STNG_MSG CHECK (CAST_LOG_TYPE_CD IN ('payload', 'result', 'errorMsg')),
    CONSTRAINT CK_PM_CASTREST_STNG_USE CHECK (USE_YN IN ('Y', 'N'))
);

COMMENT ON TABLE PMOWN.TN_PM_SMLT_CAST_LOG_STNG IS 'PM_CASTREST로그설정';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.CAST_API_TYPE_CD IS 'API유형코드';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.CAST_LOG_TYPE_CD IS '메시지유형코드';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.USE_YN IS '사용여부';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.FRST_RGTR_ID IS '최초등록자ID';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.FRST_RGTR_IP_ADDR IS '최초등록자IP주소';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.FRST_REG_DT IS '최초등록일시';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.LAST_MDFR_ID IS '최종수정자ID';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.LAST_MDFR_IP_ADDR IS '최종수정자IP주소';
COMMENT ON COLUMN PMOWN.TN_PM_SMLT_CAST_LOG_STNG.LAST_MDFCN_DT IS '최종수정일시';

CREATE TABLE PMOWN.TH_PM_SMLT_CAST_LOG (
    CAST_API_TYPE_CD VARCHAR2(30 CHAR) NOT NULL,
    CAST_LOG_TYPE_CD VARCHAR2(10 CHAR) NOT NULL,
    LOG_CN CLOB,
    FRST_RGTR_ID VARCHAR2(40),
    FRST_RGTR_IP_ADDR VARCHAR2(23),
    FRST_REG_DT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    LAST_MDFR_ID VARCHAR2(40),
    LAST_MDFR_IP_ADDR VARCHAR2(23),
    LAST_MDFCN_DT TIMESTAMP(6),
    CONSTRAINT CK_PM_SMLT_CAST_LOG_API CHECK (
        CAST_API_TYPE_CD IN ('GetResourceInformation', 'GetResource', 'SetResource')
    ),
    CONSTRAINT CK_PM_SMLT_CAST_LOG_MSG CHECK (CAST_LOG_TYPE_CD IN ('payload', 'result', 'errorMsg'))
);

COMMENT ON TABLE PMOWN.TH_PM_SMLT_CAST_LOG IS 'PM_CASTREST로그';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.CAST_API_TYPE_CD IS 'API유형코드';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.CAST_LOG_TYPE_CD IS '메시지유형코드';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.LOG_CN IS '로그내용';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.FRST_RGTR_ID IS '최초등록자ID';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.FRST_RGTR_IP_ADDR IS '최초등록자IP주소';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.FRST_REG_DT IS '최초등록일시';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.LAST_MDFR_ID IS '최종수정자ID';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.LAST_MDFR_IP_ADDR IS '최종수정자IP주소';
COMMENT ON COLUMN PMOWN.TH_PM_SMLT_CAST_LOG.LAST_MDFCN_DT IS '최종수정일시';

CREATE INDEX PMOWN.IX_PM_SMLT_CAST_LOG_REG_DT ON PMOWN.TH_PM_SMLT_CAST_LOG (FRST_REG_DT);

INSERT INTO PMOWN.TN_PM_SMLT_CAST_LOG_STNG (CAST_API_TYPE_CD, CAST_LOG_TYPE_CD, USE_YN, FRST_RGTR_ID, FRST_RGTR_IP_ADDR)
SELECT API.CAST_API_TYPE_CD, MSG.CAST_LOG_TYPE_CD, 'N', 'SYSTEM', '0.0.0.0'
FROM (
    SELECT 'GetResourceInformation' CAST_API_TYPE_CD FROM DUAL
    UNION ALL SELECT 'GetResource' FROM DUAL
    UNION ALL SELECT 'SetResource' FROM DUAL
) API
CROSS JOIN (
    SELECT 'payload' CAST_LOG_TYPE_CD FROM DUAL
    UNION ALL SELECT 'result' FROM DUAL
    UNION ALL SELECT 'errorMsg' FROM DUAL
) MSG;

COMMIT;
