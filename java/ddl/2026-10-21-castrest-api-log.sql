SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    object_count NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Run as PMOWN');
    END IF;
    SELECT COUNT(*) INTO object_count
    FROM USER_OBJECTS
    WHERE OBJECT_NAME IN (
        'TN_PM_CASTREST_LOG_STNG', 'TH_PM_CASTREST_LOG'
    );
    IF object_count != 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'CAST REST log objects already exist; inspect before applying');
    END IF;
END;
/

CREATE TABLE PMOWN.TN_PM_CASTREST_LOG_STNG (
    API_TYPE_CD VARCHAR2(30 CHAR) NOT NULL,
    MSG_TYPE_CD VARCHAR2(10 CHAR) NOT NULL,
    USE_YN CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    FRST_REG_DT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LAST_MDFCN_DT TIMESTAMP(6),
    CONSTRAINT PK_PM_CASTREST_LOG_STNG PRIMARY KEY (API_TYPE_CD, MSG_TYPE_CD),
    CONSTRAINT CK_PM_CASTREST_STNG_API CHECK (
        API_TYPE_CD IN ('GetResourceInformation', 'GetResource', 'SetResource')
    ),
    CONSTRAINT CK_PM_CASTREST_STNG_MSG CHECK (MSG_TYPE_CD IN ('payload', 'result', 'errorMsg')),
    CONSTRAINT CK_PM_CASTREST_STNG_USE CHECK (USE_YN IN ('Y', 'N'))
);

COMMENT ON TABLE PMOWN.TN_PM_CASTREST_LOG_STNG IS 'PM_CASTREST로그설정';
COMMENT ON COLUMN PMOWN.TN_PM_CASTREST_LOG_STNG.API_TYPE_CD IS 'API유형코드';
COMMENT ON COLUMN PMOWN.TN_PM_CASTREST_LOG_STNG.MSG_TYPE_CD IS '메시지유형코드';
COMMENT ON COLUMN PMOWN.TN_PM_CASTREST_LOG_STNG.USE_YN IS '사용여부';
COMMENT ON COLUMN PMOWN.TN_PM_CASTREST_LOG_STNG.FRST_REG_DT IS '최초등록일시';
COMMENT ON COLUMN PMOWN.TN_PM_CASTREST_LOG_STNG.LAST_MDFCN_DT IS '최종수정일시';

CREATE TABLE PMOWN.TH_PM_CASTREST_LOG (
    API_TYPE_CD VARCHAR2(30 CHAR) NOT NULL,
    MSG_TYPE_CD VARCHAR2(10 CHAR) NOT NULL,
    LOG_CN CLOB,
    FRST_REG_DT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_PM_CASTREST_LOG_API CHECK (
        API_TYPE_CD IN ('GetResourceInformation', 'GetResource', 'SetResource')
    ),
    CONSTRAINT CK_PM_CASTREST_LOG_MSG CHECK (MSG_TYPE_CD IN ('payload', 'result', 'errorMsg'))
);

COMMENT ON TABLE PMOWN.TH_PM_CASTREST_LOG IS 'PM_CASTREST로그';
COMMENT ON COLUMN PMOWN.TH_PM_CASTREST_LOG.API_TYPE_CD IS 'API유형코드';
COMMENT ON COLUMN PMOWN.TH_PM_CASTREST_LOG.MSG_TYPE_CD IS '메시지유형코드';
COMMENT ON COLUMN PMOWN.TH_PM_CASTREST_LOG.LOG_CN IS '로그내용';
COMMENT ON COLUMN PMOWN.TH_PM_CASTREST_LOG.FRST_REG_DT IS '최초등록일시';

CREATE INDEX PMOWN.IX_PM_CASTREST_LOG_REG_DT ON PMOWN.TH_PM_CASTREST_LOG (FRST_REG_DT);

INSERT INTO PMOWN.TN_PM_CASTREST_LOG_STNG (API_TYPE_CD, MSG_TYPE_CD, USE_YN)
SELECT API.API_TYPE_CD, MSG.MSG_TYPE_CD, 'N'
FROM (
    SELECT 'GetResourceInformation' API_TYPE_CD FROM DUAL
    UNION ALL SELECT 'GetResource' FROM DUAL
    UNION ALL SELECT 'SetResource' FROM DUAL
) API
CROSS JOIN (
    SELECT 'payload' MSG_TYPE_CD FROM DUAL
    UNION ALL SELECT 'result' FROM DUAL
    UNION ALL SELECT 'errorMsg' FROM DUAL
) MSG;

COMMIT;
