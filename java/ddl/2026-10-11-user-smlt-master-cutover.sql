DECLARE
    PROCEDURE swap_table(name VARCHAR2) IS n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME=name||'_OLD';
        IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.'||name||' RENAME TO '||name||'_OLD'; END IF;
        SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME=name||'_V2';
        IF n=1 THEN EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.'||name||'_V2 RENAME TO '||name; END IF;
    END;
BEGIN
    swap_table('TN_PM_SMLT_USER_FLT_PSG_AJMT');
