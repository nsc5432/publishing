DECLARE
    PROCEDURE unchanged(name VARCHAR2) IS n NUMBER; source_name VARCHAR2(128);
    BEGIN
        SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME=name||'_OLD';
        source_name:=CASE WHEN n=1 THEN name||'_OLD' ELSE name END;
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM (SELECT * FROM (SELECT * FROM PMOWN.'||source_name||' MINUS SELECT * FROM PMOWN.'||name||'_LGC) UNION ALL SELECT * FROM (SELECT * FROM PMOWN.'||name||'_LGC MINUS SELECT * FROM PMOWN.'||source_name||'))' INTO n;
        IF n!=0 THEN RAISE_APPLICATION_ERROR(-20015,'Source changed after stage: '||name); END IF;
    END;
BEGIN
    unchanged('TN_PM_SMLT_USER_FLT_PSG_AJMT');
    unchanged('TN_PM_SMLT_USER_CHKN_ISL');
