-- 적용 전 이 테이블을 직접 조회하는 외부 시스템·리포트가 없는지 확인한다.
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE n NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA')!='PMOWN' THEN RAISE_APPLICATION_ERROR(-20001,'PMOWN 스키마에서 실행해주세요.'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_DEPENDENCIES WHERE REFERENCED_OWNER='PMOWN' AND REFERENCED_NAME='TH_PM_SMLT_FLFMT_HSTRY';
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20002,'제거 대상 테이블을 참조하는 DB 객체가 있습니다.'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
    WHERE C.CONSTRAINT_TYPE='R' AND P.OWNER='PMOWN' AND P.TABLE_NAME='TH_PM_SMLT_FLFMT_HSTRY';
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20003,'제거 대상 테이블을 참조하는 외래키가 있습니다.'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME='TH_PM_SMLT_FLFMT_HSTRY_BAK_1018';
    IF n=0 THEN
        SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME='TH_PM_SMLT_FLFMT_HSTRY';
        IF n!=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE PMOWN.TH_PM_SMLT_FLFMT_HSTRY_BAK_1018 AS SELECT * FROM PMOWN.TH_PM_SMLT_FLFMT_HSTRY'; END IF;
    END IF;
END;
/
