CREATE TABLE PMOWN.TN_PM_SMLT_FCLT_WTNG_RSLT (
    SMLT_ID                     VARCHAR2(8) NOT NULL,
    SMLT_MDL_SN                 NUMBER(5,0) NOT NULL,
    TMNL_ID                     VARCHAR2(3) NOT NULL,
    FCLT_TYPE_CD                VARCHAR2(4) NOT NULL,
    FCLT_UNIT_CD                VARCHAR2(8) NOT NULL,
    SEC_BGNG_DT                 TIMESTAMP(0) NOT NULL,
    SEC_END_DT                  TIMESTAMP(0) NOT NULL,
    BGNG_WTNG_PSG_CNT           NUMBER(12,0),
    END_WTNG_PSG_CNT            NUMBER(12,0),
    ARR_PSG_CNT                 NUMBER(12,0),
    PRCS_PSG_CNT                NUMBER(12,0) NOT NULL,
    WTNG_PSEC_SUM               NUMBER(12,0) NOT NULL,
    WTNG_VLD_PSG_CNT            NUMBER(12,0) NOT NULL,
    PRCS_PSEC_SUM               NUMBER(12,0) NOT NULL,
    PRCS_VLD_PSG_CNT            NUMBER(12,0) NOT NULL,
    WTNG_PSG_CNT_SUM            NUMBER(12,0) NOT NULL,
    WTNG_NOCS                   NUMBER(2,0) NOT NULL,
    MAX_WTNG_PSG_CNT            NUMBER(12,0),
    BGNG_OPER_CNTOM             NUMBER(12,0),
    END_OPER_CNTOM              NUMBER(12,0),
    PRCS_CPCT                   NUMBER(12,0),
    PRCS_VLD_OPER_CNTOM_SUM     NUMBER(12,0),
    OBSRVN_MNT_CNT              NUMBER(2,0) NOT NULL,
    OBSRVN_YN                   VARCHAR2(1) NOT NULL,
    OBSRVN_RSN                  VARCHAR2(1000 CHAR),
    FRST_REG_DT                 TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LAST_MDFCN_DT               TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_SMLT_FCLT_WTNG_RSLT
        PRIMARY KEY (
            SMLT_ID, SMLT_MDL_SN, TMNL_ID, FCLT_TYPE_CD, FCLT_UNIT_CD, SEC_BGNG_DT
        ),
    CONSTRAINT FK_SMLT_FCLT_WTNG_STNG
        FOREIGN KEY (SMLT_ID, SMLT_MDL_SN)
        REFERENCES PMOWN.TN_PM_SMLT_STNG (SMLT_ID, SMLT_MDL_SN),
    CONSTRAINT CK_WTNG_RSLT_TMNL CHECK (TMNL_ID IN ('T1', 'T2')),
    CONSTRAINT CK_WTNG_RSLT_TYPE CHECK (FCLT_TYPE_CD IN ('CHKN', 'DEP')),
    CONSTRAINT CK_WTNG_RSLT_SEC CHECK (
        SEC_END_DT = SEC_BGNG_DT + INTERVAL '10' MINUTE
        AND EXTRACT(SECOND FROM SEC_BGNG_DT) = 0
        AND MOD(EXTRACT(MINUTE FROM SEC_BGNG_DT), 10) = 0
    ),
    CONSTRAINT CK_WTNG_RSLT_CNT CHECK (
        BGNG_WTNG_PSG_CNT >= 0
        AND END_WTNG_PSG_CNT >= 0
        AND ARR_PSG_CNT >= 0
        AND PRCS_PSG_CNT >= 0
        AND WTNG_PSEC_SUM >= 0
        AND WTNG_VLD_PSG_CNT BETWEEN 0 AND PRCS_PSG_CNT
        AND PRCS_PSEC_SUM >= 0
        AND PRCS_VLD_PSG_CNT BETWEEN 0 AND PRCS_PSG_CNT
        AND WTNG_PSG_CNT_SUM >= 0
        AND MAX_WTNG_PSG_CNT >= 0
        AND BGNG_OPER_CNTOM >= 0
        AND END_OPER_CNTOM >= 0
        AND PRCS_CPCT >= 0
        AND PRCS_VLD_OPER_CNTOM_SUM >= 0
    ),
    CONSTRAINT CK_WTNG_RSLT_VLD_SUM CHECK (
        (WTNG_VLD_PSG_CNT > 0 OR WTNG_PSEC_SUM = 0)
        AND (PRCS_VLD_PSG_CNT > 0 OR PRCS_PSEC_SUM = 0)
    ),
    CONSTRAINT CK_WTNG_RSLT_NOCS CHECK (
        ((FCLT_TYPE_CD = 'CHKN' AND WTNG_NOCS BETWEEN 0 AND 10)
            OR (FCLT_TYPE_CD = 'DEP' AND WTNG_NOCS BETWEEN 0 AND 1))
        AND ((WTNG_NOCS = 0 AND WTNG_PSG_CNT_SUM = 0 AND MAX_WTNG_PSG_CNT IS NULL)
            OR (WTNG_NOCS > 0 AND MAX_WTNG_PSG_CNT IS NOT NULL
                AND WTNG_PSG_CNT_SUM >= MAX_WTNG_PSG_CNT
                AND WTNG_PSG_CNT_SUM <= MAX_WTNG_PSG_CNT * WTNG_NOCS))
    ),
    CONSTRAINT CK_WTNG_RSLT_OBSRVN CHECK (
        (OBSRVN_YN = 'Y' AND OBSRVN_MNT_CNT = 10)
        OR (OBSRVN_YN = 'N' AND OBSRVN_MNT_CNT BETWEEN 0 AND 9)
    )
);

