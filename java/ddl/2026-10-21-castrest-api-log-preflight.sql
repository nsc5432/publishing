SET LONG 1000000
SET LONGCHUNKSIZE 1000000
SET LINESIZE 220
SET PAGESIZE 1000
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

SELECT SYS_CONTEXT('USERENV', 'SESSION_USER') SESSION_USER,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') CURRENT_SCHEMA
FROM DUAL;

SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS
FROM ALL_OBJECTS
WHERE OWNER = 'PMOWN' AND OBJECT_NAME IN (
    'TT_PM_CASTREST_REQ_DEBUG', 'TN_PM_CASTREST_LOG_STNG',
    'TH_PM_CASTREST_LOG', 'SQ1_TH_PM_CASTREST_LOG', 'IX_PM_CASTREST_LOG_REG_DT'
)
ORDER BY OBJECT_NAME, OBJECT_TYPE;

SELECT DBMS_METADATA.GET_DDL('TABLE', TABLE_NAME, OWNER) TABLE_DDL
FROM ALL_TABLES
WHERE OWNER = 'PMOWN' AND TABLE_NAME = 'TT_PM_CASTREST_REQ_DEBUG';

SELECT OWNER, TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHAR_LENGTH, DATA_PRECISION,
       DATA_SCALE, NULLABLE, DATA_DEFAULT
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'PMOWN' AND TABLE_NAME IN (
    'TT_PM_CASTREST_REQ_DEBUG', 'TN_PM_CASTREST_LOG_STNG', 'TH_PM_CASTREST_LOG'
)
ORDER BY TABLE_NAME, COLUMN_ID;

SELECT OWNER, TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS,
       SEARCH_CONDITION, R_OWNER, R_CONSTRAINT_NAME
FROM ALL_CONSTRAINTS
WHERE OWNER = 'PMOWN' AND TABLE_NAME IN (
    'TT_PM_CASTREST_REQ_DEBUG', 'TN_PM_CASTREST_LOG_STNG', 'TH_PM_CASTREST_LOG'
);

SELECT OWNER, INDEX_NAME, TABLE_NAME, UNIQUENESS, STATUS
FROM ALL_INDEXES
WHERE TABLE_OWNER = 'PMOWN' AND TABLE_NAME IN (
    'TT_PM_CASTREST_REQ_DEBUG', 'TN_PM_CASTREST_LOG_STNG', 'TH_PM_CASTREST_LOG'
);

SELECT GRANTOR, GRANTEE, TABLE_SCHEMA, TABLE_NAME, PRIVILEGE, GRANTABLE
FROM ALL_TAB_PRIVS
WHERE TABLE_SCHEMA = 'PMOWN' AND TABLE_NAME IN (
    'TT_PM_CASTREST_REQ_DEBUG', 'TN_PM_CASTREST_LOG_STNG',
    'TH_PM_CASTREST_LOG', 'SQ1_TH_PM_CASTREST_LOG'
)
ORDER BY TABLE_NAME, GRANTEE, PRIVILEGE;

SELECT OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME, DB_LINK
FROM ALL_SYNONYMS
WHERE TABLE_OWNER = 'PMOWN' AND TABLE_NAME = 'TT_PM_CASTREST_REQ_DEBUG';

SELECT OWNER, NAME, TYPE, REFERENCED_OWNER, REFERENCED_NAME, DEPENDENCY_TYPE
FROM ALL_DEPENDENCIES
WHERE REFERENCED_OWNER = 'PMOWN' AND REFERENCED_NAME = 'TT_PM_CASTREST_REQ_DEBUG';
