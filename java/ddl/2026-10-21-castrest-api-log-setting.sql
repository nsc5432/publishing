WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DEFINE api_type_cd = GetResource
DEFINE msg_type_cd = errorMsg
DEFINE use_yn = N

MERGE INTO PMOWN.TN_PM_CASTREST_LOG_STNG T
USING (
    SELECT '&api_type_cd' API_TYPE_CD, '&msg_type_cd' MSG_TYPE_CD, '&use_yn' USE_YN FROM DUAL
) S
ON (T.API_TYPE_CD = S.API_TYPE_CD AND T.MSG_TYPE_CD = S.MSG_TYPE_CD)
WHEN MATCHED THEN UPDATE SET T.USE_YN = S.USE_YN
WHEN NOT MATCHED THEN INSERT (API_TYPE_CD, MSG_TYPE_CD, USE_YN, FRST_RGTR_ID, FRST_RGTR_IP_ADDR)
VALUES (S.API_TYPE_CD, S.MSG_TYPE_CD, S.USE_YN, 'SYSTEM', '0.0.0.0');

COMMIT;

SELECT API_TYPE_CD, MSG_TYPE_CD, USE_YN, FRST_REG_DT, LAST_MDFCN_DT
FROM PMOWN.TN_PM_CASTREST_LOG_STNG
ORDER BY API_TYPE_CD, MSG_TYPE_CD;

UNDEFINE api_type_cd
UNDEFINE msg_type_cd
UNDEFINE use_yn
