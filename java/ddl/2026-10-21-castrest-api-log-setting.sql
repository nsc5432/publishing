WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DEFINE cast_api_type_cd = GetResource
DEFINE cast_log_type_cd = errorMsg
DEFINE use_yn = N

MERGE INTO PMOWN.TN_PM_SMLT_CAST_LOG_STNG T
USING (
    SELECT '&cast_api_type_cd' CAST_API_TYPE_CD, '&cast_log_type_cd' CAST_LOG_TYPE_CD, '&use_yn' USE_YN FROM DUAL
) S
ON (T.CAST_API_TYPE_CD = S.CAST_API_TYPE_CD AND T.CAST_LOG_TYPE_CD = S.CAST_LOG_TYPE_CD)
WHEN MATCHED THEN UPDATE SET T.USE_YN = S.USE_YN
WHEN NOT MATCHED THEN INSERT (CAST_API_TYPE_CD, CAST_LOG_TYPE_CD, USE_YN, FRST_RGTR_ID, FRST_RGTR_IP_ADDR)
VALUES (S.CAST_API_TYPE_CD, S.CAST_LOG_TYPE_CD, S.USE_YN, 'SYSTEM', '0.0.0.0');

COMMIT;

SELECT CAST_API_TYPE_CD, CAST_LOG_TYPE_CD, USE_YN, FRST_REG_DT, LAST_MDFCN_DT
FROM PMOWN.TN_PM_SMLT_CAST_LOG_STNG
ORDER BY CAST_API_TYPE_CD, CAST_LOG_TYPE_CD;

UNDEFINE cast_api_type_cd
UNDEFINE cast_log_type_cd
UNDEFINE use_yn
