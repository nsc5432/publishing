-- 화면 저장·실행과 CAST polling·상태·결과 수신을 모두 정지하고 별도 전체 백업 후 PMOWN으로 실행한다.
-- 2026-10-11 구조의 cutover가 이미 완료된 DB만 대상으로 하며 DDL은 자동 커밋된다.
DECLARE
    n NUMBER;
    PROCEDURE require_zero(query_ VARCHAR2, message_ VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE query_ INTO n;
        IF n != 0 THEN RAISE_APPLICATION_ERROR(-20001, message_ || ': ' || n); END IF;
    END;
BEGIN
    IF SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') != 'PMOWN' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Run with CURRENT_SCHEMA=PMOWN');
    END IF;
    require_zero(q'[SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_USER_MSTR WHERE SMLT_STTS IN ('New','Executing')]',
        'Drain active CAST requests');
    require_zero(q'[SELECT COUNT(*) FROM (
        SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_MSTR
        UNION ALL SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_USER_MSTR
        UNION ALL SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_STNG
    ) WHERE SMLT_ID IS NULL OR NOT REGEXP_LIKE(SMLT_ID, '^[0-9]{1,8}$') OR SMLT_ID IN ('0','00','000','0000','00000','000000','0000000','00000000')]',
        'Invalid execution ID');
    require_zero(q'[SELECT COUNT(*) FROM (
        SELECT TO_NUMBER(SMLT_ID) FROM (
            SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_USER_MSTR
            UNION ALL SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_STNG
        ) GROUP BY TO_NUMBER(SMLT_ID) HAVING COUNT(DISTINCT SMLT_ID) > 1
    )]', 'Ambiguous padded/unpadded execution IDs');
    require_zero(q'[SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_MSTR M
        WHERE NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_USER_MSTR U WHERE U.SMLT_ID=M.SMLT_ID)
          AND NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_STNG S WHERE S.SMLT_ID=M.SMLT_ID)]',
        'Master execution has no surviving source');
    require_zero(q'[SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_USER_MSTR U
        WHERE NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_MSTR M
            WHERE M.SMLT_ID=U.SMLT_ID AND M.SMLT_TYPE='WhatIf' AND M.EXCN_YMD=U.EXCN_YMD)]',
        'User execution type/date does not match master');
    require_zero(q'[SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_USER_MSTR U
        JOIN PMOWN.TN_PM_SMLT_MSTR M ON M.SMLT_ID=U.SMLT_ID
        WHERE (U.SMLT_STTS='Failed' AND M.SMLT_STTS!='Failed')
           OR (U.SMLT_STTS='Finished' AND EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_STNG S WHERE S.SMLT_ID=U.SMLT_ID) AND M.SMLT_STTS!='Finished')
           OR (U.SMLT_STTS='Finished' AND NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_STNG S WHERE S.SMLT_ID=U.SMLT_ID) AND M.SMLT_STTS NOT IN ('New','Executing'))]',
        'User execution effective status does not match master');
    require_zero(q'[SELECT COUNT(*) FROM (
        SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_STNG GROUP BY SMLT_ID
        HAVING COUNT(DISTINCT EXCN_YMD)!=1 OR COUNT(EXCN_YMD)!=COUNT(*)
            OR COUNT(DISTINCT SMLT_TYPE)!=1 OR COUNT(SMLT_TYPE)!=COUNT(*)
    )]', 'Model rows disagree on execution type/date');
    require_zero(q'[SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_STNG S
        WHERE NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_MSTR M
            WHERE M.SMLT_ID=S.SMLT_ID AND M.EXCN_YMD=S.EXCN_YMD AND M.SMLT_TYPE=S.SMLT_TYPE)
           OR (S.SMLT_TYPE='WhatIf' AND NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_USER_MSTR U WHERE U.SMLT_ID=S.SMLT_ID))
           OR (S.SMLT_TYPE!='WhatIf' AND EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_USER_MSTR U WHERE U.SMLT_ID=S.SMLT_ID))]',
        'Model source conflicts with execution classification');
    require_zero(q'[SELECT COUNT(*) FROM PMOWN.TN_PM_SMLT_MSTR M
        WHERE NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_USER_MSTR U WHERE U.SMLT_ID=M.SMLT_ID)
          AND M.SMLT_STTS!='Finished']', 'Non-user status cannot be reconstructed from saved results');
    FOR child_ IN (
        SELECT 'TN_PM_SMLT_COND_SNAPSHOT' table_name FROM DUAL
        UNION ALL SELECT 'TN_PM_SMLT_INPUT_SNAPSHOT' FROM DUAL
        UNION ALL SELECT 'TN_PM_SMLT_RSRC_LEASE' FROM DUAL
    ) LOOP
        require_zero('SELECT COUNT(*) FROM PMOWN.' || child_.table_name || ' C WHERE NOT EXISTS '
            || '(SELECT 1 FROM PMOWN.TN_PM_SMLT_USER_MSTR U WHERE U.SMLT_ID=C.SMLT_ID)',
            'Non-user child in ' || child_.table_name);
    END LOOP;
    FOR child_ IN (
        SELECT 'TN_PM_SMLT_RESULT_IDENTITY' table_name FROM DUAL
        UNION ALL SELECT 'TN_PM_SMLT_RESULT_GROUP' FROM DUAL
        UNION ALL SELECT 'TN_PM_SMLT_RSLT_DTL' FROM DUAL
        UNION ALL SELECT 'TN_PM_SMLT_RSLT_DTL_REG_EXCL' FROM DUAL
        UNION ALL SELECT 'TH_PM_SMLT_FLFMT_HSTRY' FROM DUAL
    ) LOOP
        require_zero('SELECT COUNT(*) FROM PMOWN.' || child_.table_name || ' C WHERE '
            || 'NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_USER_MSTR U WHERE U.SMLT_ID=C.SMLT_ID) '
            || 'AND NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_STNG S WHERE S.SMLT_ID=C.SMLT_ID)',
            'Orphan execution in ' || child_.table_name);
    END LOOP;
    require_zero(q'[SELECT COUNT(*) FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
        ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
        WHERE C.CONSTRAINT_TYPE='R' AND P.OWNER='PMOWN' AND P.TABLE_NAME='TN_PM_SMLT_MSTR'
          AND (C.OWNER!='PMOWN' OR C.TABLE_NAME NOT IN (
              'TN_PM_SMLT_STNG','TN_PM_SMLT_RSLT_DTL','TN_PM_SMLT_RSLT_DTL_REG_EXCL',
              'TN_PM_SMLT_USER_MSTR','TH_PM_SMLT_FLFMT_HSTRY','TN_PM_SMLT_COND_SNAPSHOT',
              'TN_PM_SMLT_INPUT_SNAPSHOT','TN_PM_SMLT_RSRC_LEASE','TN_PM_SMLT_RESULT_IDENTITY','TN_PM_SMLT_RESULT_GROUP'))]',
        'Unknown master FK requires review');
    require_zero(q'[SELECT COUNT(*) FROM ALL_DEPENDENCIES
        WHERE REFERENCED_OWNER='PMOWN' AND REFERENCED_NAME='TN_PM_SMLT_MSTR'
          AND TYPE IN ('VIEW','MATERIALIZED VIEW','PROCEDURE','FUNCTION','PACKAGE','PACKAGE BODY','TRIGGER')]',
        'Database object still depends on master');
    SELECT COUNT(*) INTO n FROM PMOWN.TN_PM_SMLT_ID_LOCK WHERE LOCK_ID='EXECUTION';
    IF n != 1 THEN RAISE_APPLICATION_ERROR(-20001, 'EXECUTION serialization lock is required'); END IF;
END;
