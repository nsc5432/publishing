    SELECT SMLT_ID, 'RESULT_IDENTITY' SOURCE_TABLE FROM PMOWN.TN_PM_SMLT_RESULT_IDENTITY
    UNION ALL SELECT SMLT_ID, 'RESULT_GROUP' FROM PMOWN.TN_PM_SMLT_RESULT_GROUP
    UNION ALL SELECT SMLT_ID, 'RESULT_DETAIL' FROM PMOWN.TN_PM_SMLT_RSLT_DTL
    UNION ALL SELECT SMLT_ID, 'RESULT_EXCLUDED' FROM PMOWN.TN_PM_SMLT_RSLT_DTL_REG_EXCL
    UNION ALL SELECT SMLT_ID, 'EXECUTION_HISTORY' FROM PMOWN.TH_PM_SMLT_FLFMT_HSTRY
) C WHERE NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_USER_MSTR U WHERE U.SMLT_ID=C.SMLT_ID)
      AND NOT EXISTS (SELECT 1 FROM PMOWN.TN_PM_SMLT_STNG S WHERE S.SMLT_ID=C.SMLT_ID);

