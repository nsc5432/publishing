DECLARE
    data_max_ NUMBER;
    sequence_count_ NUMBER;
    sequence_last_ NUMBER;
    sequence_increment_ NUMBER;
    sequence_current_ NUMBER;
    floor_ NUMBER;
    step_ NUMBER;
    PROCEDURE alter_increment(value_ NUMBER) IS
    BEGIN
        EXECUTE IMMEDIATE 'ALTER SEQUENCE PMOWN.SQ1_TN_PM_SMLT_RSLT INCREMENT BY '
            || TO_CHAR(value_, 'FM9999999990', 'NLS_NUMERIC_CHARACTERS=''.,''');
    END;
BEGIN
    SELECT NVL(MAX(TO_NUMBER(SMLT_ID)),0) INTO data_max_ FROM (
        SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_USER_MSTR
        UNION ALL SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_STNG
        UNION ALL SELECT SMLT_ID FROM PMOWN.TN_PM_SMLT_MSTR_BAK_1016
    );
    IF data_max_ >= 99999999 THEN RAISE_APPLICATION_ERROR(-20003, 'Execution ID capacity exhausted'); END IF;
    SELECT COUNT(*) INTO sequence_count_ FROM ALL_SEQUENCES
        WHERE SEQUENCE_OWNER='PMOWN' AND SEQUENCE_NAME='SQ1_TN_PM_SMLT_RSLT';
    IF sequence_count_=0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE PMOWN.SQ1_TN_PM_SMLT_RSLT START WITH '
            || TO_CHAR(data_max_+1, 'FM9999999990')
            || ' INCREMENT BY 1 MINVALUE 1 MAXVALUE 99999999 NOCYCLE NOCACHE ORDER';
    ELSE
        SELECT LAST_NUMBER, INCREMENT_BY INTO sequence_last_, sequence_increment_ FROM ALL_SEQUENCES
            WHERE SEQUENCE_OWNER='PMOWN' AND SEQUENCE_NAME='SQ1_TN_PM_SMLT_RSLT';
        IF sequence_increment_<=0 OR sequence_last_<1 OR sequence_last_>99999999 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Sequence range/direction requires manual review; never reset downward');
        END IF;
        -- 캐시 예약 상한도 보존해 이미 할당된 번호를 다시 내보내지 않는다.
        floor_:=GREATEST(data_max_, sequence_last_-1);
        EXECUTE IMMEDIATE 'ALTER SEQUENCE PMOWN.SQ1_TN_PM_SMLT_RSLT '
            || 'INCREMENT BY 1 MINVALUE 1 MAXVALUE 99999999 NOCYCLE NOCACHE ORDER';
        EXECUTE IMMEDIATE 'SELECT PMOWN.SQ1_TN_PM_SMLT_RSLT.NEXTVAL FROM DUAL' INTO sequence_current_;
        IF sequence_current_ < floor_ THEN
            step_:=floor_-sequence_current_;
            alter_increment(step_);
            BEGIN
                EXECUTE IMMEDIATE 'SELECT PMOWN.SQ1_TN_PM_SMLT_RSLT.NEXTVAL FROM DUAL' INTO sequence_current_;
            EXCEPTION WHEN OTHERS THEN
                alter_increment(1);
                RAISE;
            END;
            alter_increment(1);
        END IF;
        IF sequence_current_ >= 99999999 THEN RAISE_APPLICATION_ERROR(-20003, 'No sequence capacity remains'); END IF;
    END IF;
END;
