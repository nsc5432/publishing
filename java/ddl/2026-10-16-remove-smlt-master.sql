DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PMOWN' AND TABLE_NAME='TN_PM_SMLT_MSTR_BAK_1016';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE PMOWN.TN_PM_SMLT_MSTR_BAK_1016 AS SELECT * FROM PMOWN.TN_PM_SMLT_MSTR';
    END IF;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM (
        SELECT * FROM (SELECT * FROM PMOWN.TN_PM_SMLT_MSTR MINUS SELECT * FROM PMOWN.TN_PM_SMLT_MSTR_BAK_1016)
        UNION ALL
        SELECT * FROM (SELECT * FROM PMOWN.TN_PM_SMLT_MSTR_BAK_1016 MINUS SELECT * FROM PMOWN.TN_PM_SMLT_MSTR)
    )' INTO n;
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20002, 'Master backup differs; do not overwrite backup'); END IF;
END;
