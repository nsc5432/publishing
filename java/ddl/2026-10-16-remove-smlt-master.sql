DECLARE
    n NUMBER;
BEGIN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM (
        SELECT * FROM (SELECT * FROM PMOWN.TN_PM_SMLT_MSTR MINUS SELECT * FROM PMOWN.TN_PM_SMLT_MSTR_BAK_1016)
        UNION ALL
        SELECT * FROM (SELECT * FROM PMOWN.TN_PM_SMLT_MSTR_BAK_1016 MINUS SELECT * FROM PMOWN.TN_PM_SMLT_MSTR)
    )' INTO n;
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20005, 'Master changed during cutover'); END IF;
    SELECT COUNT(*) INTO n FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
        ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
        WHERE C.CONSTRAINT_TYPE='R' AND P.OWNER='PMOWN' AND P.TABLE_NAME='TN_PM_SMLT_MSTR';
    IF n!=0 THEN RAISE_APPLICATION_ERROR(-20005, 'Master FK remains'); END IF;
    EXECUTE IMMEDIATE 'DROP TABLE PMOWN.TN_PM_SMLT_MSTR';
    DBMS_OUTPUT.PUT_LINE('Master removed; preserve TN_PM_SMLT_MSTR_BAK_1016 and full backup.');
END;
