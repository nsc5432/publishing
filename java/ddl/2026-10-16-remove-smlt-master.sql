DECLARE
    n NUMBER;
    PROCEDURE add_user_fk(table_ VARCHAR2, name_ VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO n FROM ALL_CONSTRAINTS WHERE OWNER='PMOWN' AND CONSTRAINT_NAME=name_;
        IF n=0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.' || table_ || ' ADD CONSTRAINT ' || name_
                || ' FOREIGN KEY (SMLT_ID) REFERENCES PMOWN.TN_PM_SMLT_USER_MSTR(SMLT_ID) DEFERRABLE INITIALLY DEFERRED';
        END IF;
        SELECT COUNT(*) INTO n FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
            ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
            WHERE C.OWNER='PMOWN' AND C.TABLE_NAME=table_ AND C.CONSTRAINT_NAME=name_
              AND C.CONSTRAINT_TYPE='R' AND C.STATUS='ENABLED' AND C.VALIDATED='VALIDATED'
              AND C.DEFERRABLE='DEFERRABLE' AND C.DEFERRED='DEFERRED'
              AND P.OWNER='PMOWN' AND P.TABLE_NAME='TN_PM_SMLT_USER_MSTR'
              AND (SELECT COUNT(*) FROM ALL_CONS_COLUMNS CC WHERE CC.OWNER=C.OWNER AND CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME)=1
              AND EXISTS (SELECT 1 FROM ALL_CONS_COLUMNS CC WHERE CC.OWNER=C.OWNER AND CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME AND CC.COLUMN_NAME='SMLT_ID' AND CC.POSITION=1)
              AND EXISTS (SELECT 1 FROM ALL_CONS_COLUMNS PC WHERE PC.OWNER=P.OWNER AND PC.CONSTRAINT_NAME=P.CONSTRAINT_NAME AND PC.COLUMN_NAME='SMLT_ID' AND PC.POSITION=1);
        IF n!=1 THEN RAISE_APPLICATION_ERROR(-20004, 'Unexpected user FK definition: ' || name_); END IF;
    END;
BEGIN
    FOR fk_ IN (
        SELECT C.OWNER, C.TABLE_NAME, C.CONSTRAINT_NAME FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
            ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
        WHERE C.CONSTRAINT_TYPE='R' AND P.OWNER='PMOWN' AND P.TABLE_NAME='TN_PM_SMLT_MSTR'
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE ' || DBMS_ASSERT.ENQUOTE_NAME(fk_.OWNER)
            || '.' || DBMS_ASSERT.ENQUOTE_NAME(fk_.TABLE_NAME)
            || ' DROP CONSTRAINT ' || DBMS_ASSERT.ENQUOTE_NAME(fk_.CONSTRAINT_NAME);
    END LOOP;
    -- 발행 자식이 사용자 요청보다 먼저 INSERT되므로 FK 검사는 커밋 때 수행한다.
    add_user_fk('TN_PM_SMLT_COND_SNAPSHOT','FK_COND_USER');
    add_user_fk('TN_PM_SMLT_INPUT_SNAPSHOT','FK_INPUT_USER');
    add_user_fk('TN_PM_SMLT_RSRC_LEASE','FK_LEASE_USER');
END;
