CREATE OR REPLACE PROCEDURE PMOWN.PR_PM_SMLT_RSLT_CLEANUP
IS
    C_DELETE_LIMIT CONSTANT PLS_INTEGER := 10000;
    V_TARGET_YMD PMOWN.TN_PM_SMLT_STNG.EXCN_YMD%TYPE;
    V_MIN_SMLT_ID NUMBER;
    V_MAX_SMLT_ID NUMBER;
    V_DELETED_ROWS PLS_INTEGER;
BEGIN
    V_TARGET_YMD := TO_CHAR(SYSDATE - 1, 'YYYYMMDD');

    -- 앞자리 0이 있는 기존 ID와 없는 신규 ID를 숫자로 비교한다.
    SELECT MIN(TO_NUMBER(SMLT_ID)), MAX(TO_NUMBER(SMLT_ID))
      INTO V_MIN_SMLT_ID, V_MAX_SMLT_ID
      FROM PMOWN.TN_PM_SMLT_STNG
     WHERE EXCN_YMD = V_TARGET_YMD
       AND SMLT_TYPE = 'Auto';

    IF V_MIN_SMLT_ID IS NULL OR V_MIN_SMLT_ID = V_MAX_SMLT_ID THEN
        RETURN;
    END IF;

    FOR R IN (
        SELECT SMLT_ID
          FROM PMOWN.TN_PM_SMLT_STNG
         WHERE EXCN_YMD = V_TARGET_YMD
           AND SMLT_TYPE = 'Auto'
           AND TO_NUMBER(SMLT_ID) > V_MIN_SMLT_ID
           AND TO_NUMBER(SMLT_ID) < V_MAX_SMLT_ID
         GROUP BY SMLT_ID
         ORDER BY TO_NUMBER(SMLT_ID), SMLT_ID
    ) LOOP
        LOOP
            DELETE FROM PMOWN.TN_PM_SMLT_RSLT_DTL
             WHERE SMLT_ID = R.SMLT_ID
               AND ROWNUM <= C_DELETE_LIMIT;

            V_DELETED_ROWS := SQL%ROWCOUNT;

            EXIT WHEN V_DELETED_ROWS = 0;

            COMMIT;
        END LOOP;

        -- 중단 후 재실행 시 남은 상세를 찾을 수 있도록 설정은 마지막에 삭제한다.
        DELETE FROM PMOWN.TN_PM_SMLT_STNG
         WHERE SMLT_ID = R.SMLT_ID
           AND EXCN_YMD = V_TARGET_YMD
           AND SMLT_TYPE = 'Auto';

        COMMIT;
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/
