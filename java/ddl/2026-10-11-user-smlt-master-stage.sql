MERGE INTO PMOWN.TN_PM_SMLT_LEGACY_COND_MAP T USING (
    SELECT A.SMLT_ID OLD_SMLT_ID, A.TMNL_ID, 'FLT_PSG' AREA_CD,
        MIN(A.FRST_RGTR_ID) KEEP (DENSE_RANK FIRST ORDER BY A.FRST_REG_DT NULLS LAST) OWNER_USER_ID,
        MAX(S.EXCN_YMD) EXCN_YMD, MAX(NVL(A.LAST_MDFCN_DT,A.FRST_REG_DT)) SAVE_DT,
        CASE WHEN NOT REGEXP_LIKE(A.SMLT_ID,'^[0-9]{1,8}$') THEN 'INVALID_ID'
             WHEN COUNT(DISTINCT S.EXCN_YMD) != 1 THEN 'MISSING_OR_AMBIGUOUS_DATE'
             WHEN COUNT(DISTINCT A.FRST_RGTR_ID) KEEP (DENSE_RANK FIRST ORDER BY A.FRST_REG_DT NULLS LAST) != 1 THEN 'MISSING_OR_AMBIGUOUS_OWNER'
             WHEN MIN(A.FRST_RGTR_ID) KEEP (DENSE_RANK FIRST ORDER BY A.FRST_REG_DT NULLS LAST) IS NULL THEN 'MISSING_OWNER' END REASON
    FROM PMOWN.TN_PM_SMLT_USER_FLT_PSG_AJMT_LGC A LEFT JOIN PMOWN.TN_PM_SMLT_STNG S ON A.SMLT_ID=S.SMLT_ID
    GROUP BY A.SMLT_ID,A.TMNL_ID
) S ON (T.OLD_SMLT_ID=S.OLD_SMLT_ID AND T.TMNL_ID=S.TMNL_ID AND T.AREA_CD=S.AREA_CD)
WHEN NOT MATCHED THEN INSERT (OLD_SMLT_ID,TMNL_ID,AREA_CD,OWNER_USER_ID,EXCN_YMD,SAVE_DT,SELECTED_YN,REASON)
