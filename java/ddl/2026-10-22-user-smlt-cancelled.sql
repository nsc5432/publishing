WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    constraint_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO constraint_count
    FROM ALL_CONSTRAINTS
    WHERE OWNER = 'PMOWN'
      AND TABLE_NAME = 'TN_PM_SMLT_USER_MSTR'
      AND CONSTRAINT_NAME = 'TN_PM_SMLT_USER_MSTR_CK2';

    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_USER_MSTR ADD CONSTRAINT TN_PM_SMLT_USER_MSTR_CK2 '
            || 'CHECK (SMLT_STTS IN (''New'', ''Executing'', ''Finished'', ''Failed'', ''Cancelled'')) ENABLE VALIDATE';
    END IF;

    FOR constraint_row IN (
        SELECT CONSTRAINT_NAME
        FROM ALL_CONSTRAINTS
        WHERE OWNER = 'PMOWN'
          AND TABLE_NAME = 'TN_PM_SMLT_USER_MSTR'
          AND CONSTRAINT_TYPE = 'C'
          AND CONSTRAINT_NAME IN ('TN_PM_SMLT_USER_MSTR_CK1', 'TN_PM_SMLT_USER_MSTR_V2_CK1')
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE PMOWN.TN_PM_SMLT_USER_MSTR DROP CONSTRAINT '
            || constraint_row.CONSTRAINT_NAME;
    END LOOP;
END;
/
